#!/usr/bin/env python3
"""Build, verify, and replay a corpus for S3 workload experiments.

Run with --root PATH and a build, verify, reset, step, or check-history
command. The corpus contains reference files and generated JSONL,
SQLite, and ZIP data. Only the Python standard library is required.

Generated bytes are repeatable test data. The seed is public, and each
manifest records the seed and runtime versions used to build its corpus.
"""

from __future__ import annotations

import argparse
import base64
import bz2
import contextlib
import hashlib
import json
import os
import platform
import shutil
import sqlite3
import struct
import tarfile
import tempfile
import urllib.request
import zipfile
import zlib
from collections.abc import Iterable, Iterator
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

MIB = 1024 * 1024
SEED = b"s3-workload-corpus-v1"
RECORD_SIZE = 512
JSONL_FILE_COUNT = 256
JSONL_FILE_SIZE = 512 * 1024
SQLITE_ROW_COUNT = 65_536
SQLITE_PAYLOAD_SIZE = 1536
SQLITE_UPDATE_ROWS = 2048
ZIP_MEMBER_COUNT = 16
ZIP_MEMBER_SIZE = 4 * MIB
REFERENCE = {
    "dickens": (10192446, "88334708559f6db57d79096bc0aca07e", "dickens.txt"),
    "mozilla": (51220480, "c7789a2097f1ff944b0c737430a339b3", "mozilla.tar"),
    "reymont": (6627202, "d8f54d78105079775f32d76dc55fc671", "reymont.pdf"),
    "samba": (21606400, "154eaea7ea70e89f6339ff0abf4112ca", "samba.tar"),
}
GROUP_STEPS = {
    "jsonl": 240,
    "sqlite": 240,
    "zip01": 120,
    "zip02": 120,
    "zip03": 120,
}


@contextlib.contextmanager
def _temp_path(path: Path) -> Iterator[Path]:
    """Create a nearby temporary file and remove it on exit."""
    descriptor, name = tempfile.mkstemp(
        dir=path.parent, prefix=f".{path.name}.", suffix=".tmp"
    )
    os.close(descriptor)
    temporary = Path(name)
    try:
        yield temporary
    finally:
        temporary.unlink(missing_ok=True)


def _write_text(path: Path, text: str) -> None:
    """Replace a UTF-8 text file after its new contents are written."""
    with _temp_path(path) as temporary:
        temporary.write_text(text, encoding="utf-8", newline="\n")
        temporary.replace(path)


def _read_seed(root: Path) -> bytes:
    """Use the saved seed when replaying an existing corpus."""
    manifest = root / "manifest.json"
    if manifest.exists():
        data = json.loads(manifest.read_text(encoding="utf-8"))
        return data["data_seed"].encode("utf-8")
    return SEED


def runtime_info() -> dict[str, str]:
    """Return the versions that can affect generated file contents."""
    return {
        "python": platform.python_version(),
        "sqlite": sqlite3.sqlite_version,
        "zlib": zlib.ZLIB_RUNTIME_VERSION,
        "generator": "s3sync-corpus-v1",
    }


def file_hash(path: Path, name: str = "sha256") -> str:
    """Return a file checksum, using SHA-256 unless name is supplied."""
    checksum = hashlib.new(name, usedforsecurity=False)
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(MIB), b""):
            checksum.update(block)
    return checksum.hexdigest()


def make_test_bytes(
    namespace: str,
    revision: int,
    record: int,
    length: int,
    seed: bytes = SEED,
) -> bytes:
    """Return repeatable test bytes for one record and revision."""
    key = (
        seed
        + b"\0"
        + str(namespace).encode("utf-8")
        + b"\0"
        + struct.pack("<QQ", revision, record)
    )
    return hashlib.shake_256(key).digest(length)


def make_records(
    namespace: str, revision: int, count: int, seed: bytes = SEED
) -> Iterator[bytes]:
    """Yield count JSON records of 512 bytes, including each newline."""
    for number in range(count):
        prefix = (
            f'{{"id":"{number:010d}","rev":"{revision:06d}","data":"'
        ).encode("utf-8")
        width = RECORD_SIZE - len(prefix) - 3
        payload = base64.b64encode(
            make_test_bytes(
                namespace, revision, number, ((width + 3) // 4) * 3, seed
            )
        )[:width]
        line = prefix + payload + b'"}\n'
        if len(line) != RECORD_SIZE:
            raise ValueError("Generated record has an invalid size")
        yield line


def write_jsonl(
    path: Path,
    namespace: str,
    revision: int,
    size: int,
    seed: bytes = SEED,
) -> None:
    """Write JSONL data; size must be a nonnegative multiple of 512."""
    if size < 0 or size % RECORD_SIZE:
        raise ValueError("JSONL size must be a nonnegative multiple of 512")
    with path.open("wb") as stream:
        stream.writelines(
            make_records(namespace, revision, size // RECORD_SIZE, seed)
        )


def compress_member(
    namespace: str, revision: int, seed: bytes = SEED
) -> tuple[bytes, int, int]:
    """Return raw DEFLATE data, its original size, and its CRC-32."""
    data = b"".join(
        make_records(namespace, revision, ZIP_MEMBER_SIZE // RECORD_SIZE, seed)
    )
    compressor = zlib.compressobj(6, zlib.DEFLATED, -15)
    compressed = compressor.compress(data) + compressor.flush()
    return compressed, len(data), zlib.crc32(data) & 0xFFFFFFFF


def write_zip(
    path: Path,
    source: Path | None = None,
    changed: int | None = None,
    revision: int = 0,
    seed: bytes = SEED,
) -> None:
    """Build a ZIP archive or replace one JSONL member in source.

    Copy unchanged DEFLATE streams without recompressing them. Rebuild
    headers and the central directory with fixed timestamps and modes.
    Replace path only after the new archive and source files are closed.
    """
    with _temp_path(path) as temporary:
        with contextlib.ExitStack() as stack:
            original = None
            raw = None
            if source is not None:
                original = stack.enter_context(zipfile.ZipFile(source))
                raw = stack.enter_context(source.open("rb"))
            output = stack.enter_context(temporary.open("wb"))
            central = []
            for number in range(ZIP_MEMBER_COUNT):
                name = f"records_{number:02d}.jsonl"
                encoded = name.encode("utf-8")
                if original is not None and number != changed:
                    info = original.getinfo(name)
                    if (
                        info.compress_type != zipfile.ZIP_DEFLATED
                        or info.flag_bits & 1
                    ):
                        raise ValueError(f"Unsupported ZIP member: {name}")
                    raw.seek(info.header_offset)
                    header = raw.read(30)
                    if len(header) != 30:
                        raise ValueError(f"Incomplete ZIP header: {name}")
                    values = struct.unpack("<IHHHHHIIIHH", header)
                    if values[0] != 0x04034B50:
                        raise ValueError(f"Invalid ZIP header: {name}")
                    raw.seek(values[-2] + values[-1], 1)
                    packed = raw.read(info.compress_size)
                    if len(packed) != info.compress_size:
                        raise ValueError(f"Incomplete ZIP member: {name}")
                    size, crc = info.file_size, info.CRC
                else:
                    member_revision = revision if number == changed else 0
                    packed, size, crc = compress_member(
                        path.stem + "/" + name, member_revision, seed
                    )
                offset = output.tell()
                output.write(
                    struct.pack(
                        "<IHHHHHIIIHH",
                        0x04034B50,
                        20,
                        0x800,
                        8,
                        0,
                        33,
                        crc,
                        len(packed),
                        size,
                        len(encoded),
                        0,
                    )
                )
                output.write(encoded)
                output.write(packed)
                central.append((encoded, crc, len(packed), size, offset))
            start = output.tell()
            for name, crc, packed_size, size, offset in central:
                output.write(
                    struct.pack(
                        "<IHHHHHHIIIHHHHHII",
                        0x02014B50,
                        788,
                        20,
                        0x800,
                        8,
                        0,
                        33,
                        crc,
                        packed_size,
                        size,
                        len(name),
                        0,
                        0,
                        0,
                        0,
                        0o100644 << 16,
                        offset,
                    )
                )
                output.write(name)
            length = output.tell() - start
            output.write(
                struct.pack(
                    "<IHHHHIIH",
                    0x06054B50,
                    0,
                    0,
                    ZIP_MEMBER_COUNT,
                    ZIP_MEMBER_COUNT,
                    length,
                    start,
                    0,
                )
            )
        temporary.replace(path)


def download_reference(root: Path, name: str) -> dict:
    """Download, unpack, and verify one Silesia reference file.

    Reuse completed downloads. Check the unpacked size and source MD5
    before replacing the reference file, then return its metadata.
    """
    size, md5, filename = REFERENCE[name]
    destination = root / "base" / "reference" / filename
    destination.parent.mkdir(parents=True, exist_ok=True)
    url = f"https://sun.aei.polsl.pl/~sdeor/corpus/{name}.bz2"
    cache = root / "downloads" / f"{name}.bz2"
    cache.parent.mkdir(parents=True, exist_ok=True)
    if not cache.exists():
        with _temp_path(cache) as temporary:
            with (
                urllib.request.urlopen(url, timeout=120) as source,
                temporary.open("wb") as output,
            ):
                shutil.copyfileobj(source, output, MIB)
            temporary.replace(cache)
    with _temp_path(destination) as temporary:
        with bz2.open(cache, "rb") as source, temporary.open("wb") as output:
            shutil.copyfileobj(source, output, MIB)
        if (
            temporary.stat().st_size != size
            or file_hash(temporary, "md5") != md5
        ):
            raise ValueError(f"Reference size or source MD5 mismatch: {name}")
        temporary.replace(destination)
    print(f"Reference verified: {filename}", flush=True)
    return {
        "path": "reference/" + filename,
        "source": url,
        "source_name": name,
        "source_md5": md5,
        "bytes": size,
        "sha256": file_hash(destination),
    }


def build_database(path: Path) -> None:
    """Create the initial SQLite table with fixed row and payload sizes."""
    with contextlib.closing(sqlite3.connect(path)) as database:
        database.execute("PRAGMA page_size=4096")
        database.execute("PRAGMA journal_mode=DELETE")
        database.execute("PRAGMA auto_vacuum=NONE")
        database.execute(
            "CREATE TABLE items("
            "id INTEGER PRIMARY KEY, "
            "revision INTEGER NOT NULL, "
            "payload BLOB NOT NULL)"
        )
        for start in range(0, SQLITE_ROW_COUNT, SQLITE_UPDATE_ROWS):
            database.executemany(
                "INSERT INTO items VALUES(?,?,?)",
                (
                    (
                        number,
                        0,
                        make_test_bytes(
                            "sqlite", 0, number, SQLITE_PAYLOAD_SIZE
                        ),
                    )
                    for number in range(start, start + SQLITE_UPDATE_ROWS)
                ),
            )
        database.commit()


def write_history(root: Path) -> None:
    """Write update events and light and heavy restore schedules."""
    history = root / "history"
    history.mkdir(exist_ok=True)
    for group, steps in GROUP_STEPS.items():
        events = []
        for step in range(1, steps + 1):
            event = {"group": group, "step": step}
            if group == "jsonl":
                event.update(
                    operation="replace_jsonl_files",
                    file_indices=[
                        (step * 17 + offset * 29) % JSONL_FILE_COUNT
                        for offset in range(8)
                    ],
                    regenerated_bytes=4 * MIB,
                )
            elif group == "sqlite":
                event.update(
                    operation="update_rows",
                    row_count=SQLITE_UPDATE_ROWS,
                    first=(step * 7919) % SQLITE_ROW_COUNT,
                    stride=31,
                    logical_payload_bytes=(
                        SQLITE_UPDATE_ROWS * SQLITE_PAYLOAD_SIZE
                    ),
                )
            else:
                event.update(
                    operation="replace_zip_member",
                    member_index=(step * 7) % ZIP_MEMBER_COUNT,
                    uncompressed_member_bytes=ZIP_MEMBER_SIZE,
                )
            events.append(event)
        _write_text(
            history / f"{group}.jsonl",
            "".join(
                json.dumps(event, sort_keys=True) + "\n" for event in events
            ),
        )
        for period, name in [(20, "read_light"), (1, "read_heavy")]:
            trace = []
            for event in events:
                trace.append(
                    {"action": "write", "group": group, "step": event["step"]}
                )
                if event["step"] % period == 0 or event["step"] == steps:
                    trace.append(
                        {
                            "action": "cold_restore",
                            "group": group,
                            "step": event["step"],
                        }
                    )
            _write_text(
                history / f"{group}.{name}.jsonl",
                "".join(
                    json.dumps(event, sort_keys=True) + "\n" for event in trace
                ),
            )


def build(root: Path) -> None:
    """Build base files and histories, then write their manifest.

    Refuse to overwrite an existing manifest.
    """
    base = root / "base"
    if (root / "manifest.json").exists():
        raise ValueError(
            "Corpus already exists; verify it instead of overwriting"
        )
    root.mkdir(parents=True, exist_ok=True)
    for directory in ["jsonl", "sqlite", "zip"]:
        (base / directory).mkdir(parents=True, exist_ok=True)
    with ThreadPoolExecutor(max_workers=4) as pool:
        sources = list(
            pool.map(lambda name: download_reference(root, name), REFERENCE)
        )
    for number in range(JSONL_FILE_COUNT):
        path = base / "jsonl" / f"records_{number:04d}.jsonl"
        write_jsonl(path, "jsonl/" + path.name, 0, JSONL_FILE_SIZE)
    print("JSONL complete", flush=True)
    build_database(base / "sqlite" / "catalog.sqlite")
    print("SQLite complete", flush=True)
    for number in range(1, 4):
        path = base / "zip" / f"zip{number:02d}.zip"
        write_zip(path)
        print("ZIP complete:", path.name, flush=True)
    write_history(root)
    paths = [base / "reference" / item[2] for item in REFERENCE.values()]
    for group in GROUP_STEPS:
        paths.extend(group_paths(root, group, "base"))
    files = [
        {
            "path": path.relative_to(base).as_posix(),
            "bytes": path.stat().st_size,
            "sha256": file_hash(path),
        }
        for path in sorted(paths)
    ]
    manifest = {
        "dataset": "s3sync-corpus-v1",
        "runtime": runtime_info(),
        "data_seed": SEED.decode("utf-8"),
        "base_bytes": sum(item["bytes"] for item in files),
        "base_files": len(files),
        "files": files,
        "reference_sources": sources,
        "groups": GROUP_STEPS,
        "note": (
            "Reference files are immutable. Histories describe controlled "
            "synthetic workloads, not recorded user activity."
        ),
    }
    _write_text(root / "manifest.json", json.dumps(manifest, indent=2))
    print(
        "BASE BYTES",
        manifest["base_bytes"],
        "FILES",
        manifest["base_files"],
        flush=True,
    )


def group_paths(root: Path, group: str, area: str) -> list[Path]:
    """Return the expected files for a group in the base or work area."""
    if group not in GROUP_STEPS:
        raise ValueError(f"Unknown group: {group}")
    directory = root / area
    if group == "jsonl":
        return [
            directory / "jsonl" / f"records_{number:04d}.jsonl"
            for number in range(JSONL_FILE_COUNT)
        ]
    if group == "sqlite":
        return [directory / "sqlite" / "catalog.sqlite"]
    return [directory / "zip" / f"{group}.zip"]


def reset(root: Path, group: str) -> None:
    """Copy base files into work and set the selected group to step zero."""
    if group == "all":
        for name in GROUP_STEPS:
            reset(root, name)
        return
    paths = group_paths(root, group, "base")
    for source in paths:
        if not source.is_file():
            raise FileNotFoundError(source)
    for source in paths:
        destination = root / "work" / source.relative_to(root / "base")
        destination.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(source, destination)
    state = root / "work" / "state"
    state.mkdir(parents=True, exist_ok=True)
    _write_text(state / f"{group}.json", '{"step":0}')


def apply_step(root: Path, group: str, step: int) -> None:
    """Apply the next update and save its step after the writes succeed.

    Steps must be applied in order after reset. The manifest seed keeps
    existing corpora repeatable when the default seed changes.
    """
    if not 1 <= step <= GROUP_STEPS[group]:
        raise ValueError("Step out of range")
    state = root / "work" / "state" / f"{group}.json"
    current = json.loads(state.read_text(encoding="utf-8"))["step"]
    if current != step - 1:
        raise ValueError(
            f"Expected previous step {step - 1}, got {current}; "
            "reset or apply steps in order"
        )
    seed = _read_seed(root)
    if group == "jsonl":
        for offset in range(8):
            number = (step * 17 + offset * 29) % JSONL_FILE_COUNT
            path = root / "work" / "jsonl" / f"records_{number:04d}.jsonl"
            write_jsonl(
                path, "jsonl/" + path.name, step, JSONL_FILE_SIZE, seed
            )
    elif group == "sqlite":
        path = root / "work" / "sqlite" / "catalog.sqlite"
        if not path.is_file():
            raise FileNotFoundError(path)
        with contextlib.closing(sqlite3.connect(path)) as database:
            database.execute("PRAGMA journal_mode=DELETE")
            database.executemany(
                "UPDATE items SET revision=?,payload=? WHERE id=?",
                (
                    (
                        step,
                        make_test_bytes(
                            "sqlite", step, number, SQLITE_PAYLOAD_SIZE, seed
                        ),
                        number,
                    )
                    for number in (
                        (step * 7919 + offset * 31) % SQLITE_ROW_COUNT
                        for offset in range(SQLITE_UPDATE_ROWS)
                    )
                ),
            )
            database.commit()
    else:
        path = root / "work" / "zip" / f"{group}.zip"
        write_zip(
            path,
            source=path,
            changed=(step * 7) % ZIP_MEMBER_COUNT,
            revision=step,
            seed=seed,
        )
    _write_text(state, json.dumps({"step": step}))


def _check_records(lines: Iterable[bytes], expected: int, source: str) -> None:
    """Check JSON records, their sizes, IDs, and total count."""
    count = 0
    for number, line in enumerate(lines):
        if len(line) != RECORD_SIZE:
            raise ValueError(f"Invalid record size in {source}: {number}")
        row = json.loads(line)
        if int(row["id"]) != number:
            raise ValueError(f"Invalid record ID in {source}: {number}")
        count += 1
    if count != expected:
        raise ValueError(
            f"Expected {expected} records in {source}, got {count}"
        )


def check_group(
    root: Path, group: str, area: str = "work", thorough: bool = False
) -> None:
    """Check a group's file structure and fixed record counts.

    With thorough enabled, also decompress and check every ZIP member.
    """
    paths = group_paths(root, group, area)
    if group == "jsonl":
        actual = set((root / area / "jsonl").glob("*.jsonl"))
        if actual != set(paths):
            raise ValueError("JSONL file set does not match the corpus layout")
        for path in paths:
            with path.open("rb") as stream:
                _check_records(
                    stream, JSONL_FILE_SIZE // RECORD_SIZE, str(path)
                )
    elif group == "sqlite":
        uri = paths[0].resolve().as_uri() + "?mode=ro"
        with contextlib.closing(sqlite3.connect(uri, uri=True)) as database:
            if (
                database.execute("PRAGMA integrity_check").fetchone()[0]
                != "ok"
            ):
                raise ValueError("SQLite integrity check failed")
            sizes = database.execute(
                "SELECT count(*),min(length(payload)),max(length(payload)) "
                "FROM items"
            ).fetchone()
            if sizes != (
                SQLITE_ROW_COUNT,
                SQLITE_PAYLOAD_SIZE,
                SQLITE_PAYLOAD_SIZE,
            ):
                raise ValueError("SQLite row count or payload size mismatch")
    else:
        with zipfile.ZipFile(paths[0]) as archive:
            expected = [
                f"records_{number:02d}.jsonl"
                for number in range(ZIP_MEMBER_COUNT)
            ]
            if archive.namelist() != expected:
                raise ValueError("ZIP members do not match the corpus layout")
            if thorough:
                bad_member = archive.testzip()
                if bad_member is not None:
                    raise ValueError(f"ZIP checksum mismatch: {bad_member}")
                for info in archive.infolist():
                    with archive.open(info) as stream:
                        _check_records(
                            stream,
                            ZIP_MEMBER_SIZE // RECORD_SIZE,
                            f"{paths[0]}:{info.filename}",
                        )


def verify(root: Path) -> None:
    """Check base file sizes, hashes, generated formats, and TAR contents."""
    manifest = json.loads((root / "manifest.json").read_text(encoding="utf-8"))
    for item in manifest["files"]:
        path = root / "base" / item["path"]
        if (
            path.stat().st_size != item["bytes"]
            or file_hash(path) != item["sha256"]
        ):
            raise ValueError(
                f"Base file size or SHA-256 mismatch: {item['path']}"
            )
    for group in GROUP_STEPS:
        check_group(root, group, "base", thorough=True)
    for name in ["mozilla.tar", "samba.tar"]:
        with tarfile.open(root / "base" / "reference" / name) as archive:
            if not archive.getmembers():
                raise ValueError(f"Empty reference archive: {name}")
    print("All initial file hashes and formats verified", flush=True)


def file_states(root: Path, group: str) -> list[dict]:
    """Return working file paths, sizes, and SHA-256 hashes for a group."""
    return [
        {
            "path": path.relative_to(root / "work").as_posix(),
            "bytes": path.stat().st_size,
            "sha256": file_hash(path),
        }
        for path in group_paths(root, group, "work")
    ]


def check_history(root: Path, selected: str, limit: int | None = None) -> None:
    """Reset and replay selected groups, saving checkpoint hashes.

    Check formats every 20 updates and at the final step. A positive
    limit caps the replay; omit it to replay each complete history.
    Checkpoint hashes describe the replay, without an external baseline.
    """
    if limit is not None and limit < 1:
        raise ValueError("History limit must be positive")
    groups = list(GROUP_STEPS) if selected == "all" else [selected]
    results = {
        "runtime": runtime_info(),
        "groups": {},
        "note": (
            "File formats are checked and hashes recorded every 20 updates "
            "and at the last version. This replay does not measure S3, "
            "encryption, or delta performance."
        ),
    }
    for group in groups:
        reset(root, group)
        end = GROUP_STEPS[group]
        if limit is not None:
            end = min(limit, end)
        checkpoints = []
        for step in range(1, end + 1):
            apply_step(root, group, step)
            if step % 20 == 0 or step == end:
                check_group(root, group, thorough=True)
                checkpoints.append(
                    {"step": step, "files": file_states(root, group)}
                )
                print("History verified:", group, step, "/", end, flush=True)
        results["groups"][group] = {
            "verified_steps": end,
            "checkpoints": checkpoints,
        }
    filename = (
        "history_validation.json"
        if limit is None
        else "history_sample_validation.json"
    )
    destination = root / filename
    _write_text(destination, json.dumps(results, indent=2))
    print("Validation saved:", destination, flush=True)


def main() -> None:
    """Parse command-line arguments and run the requested corpus action."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--root", type=Path, default=Path(__file__).resolve().parent
    )
    commands = parser.add_subparsers(dest="command", required=True)
    commands.add_parser("build", help="Build the base corpus and histories")
    commands.add_parser("verify", help="Verify the base corpus")
    reset_parser = commands.add_parser("reset", help="Restore working files")
    reset_parser.add_argument(
        "--group", choices=["all", *GROUP_STEPS], default="all"
    )
    step_parser = commands.add_parser("step", help="Apply the next update")
    step_parser.add_argument(
        "--group", choices=list(GROUP_STEPS), required=True
    )
    step_parser.add_argument("--number", type=int, required=True)
    history_parser = commands.add_parser(
        "check-history", help="Replay histories and record checkpoints"
    )
    history_parser.add_argument(
        "--group", choices=["all", *GROUP_STEPS], default="all"
    )
    history_parser.add_argument("--limit", type=int)
    args = parser.parse_args()
    if args.command == "check-history" and (
        args.limit is not None and args.limit < 1
    ):
        parser.error("--limit must be positive")
    root = args.root.resolve()
    if args.command == "build":
        build(root)
    elif args.command == "verify":
        verify(root)
    elif args.command == "reset":
        reset(root, args.group)
    elif args.command == "step":
        apply_step(root, args.group, args.number)
    elif args.command == "check-history":
        check_history(root, args.group, args.limit)


if __name__ == "__main__":
    main()
